package com.peopledesk.dao;

import com.peopledesk.config.DBConnection;
import com.peopledesk.model.Employee;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

/**
 * All database work for the "employees" table (the "DAO" = Data Access Object pattern).
 * Servlets call these methods and never write SQL themselves.
 * Every query that uses user input is a PreparedStatement with ? placeholders.
 */
public class EmployeeDAO {

    /** MySQL error code for "duplicate entry" (unique key violated). */
    public static final int MYSQL_DUPLICATE_ENTRY = 1062;

    private static final String COLUMNS =
            "id, name, email, phone, department, job_title, salary, joining_date, created_at";

    /** All employees, oldest first. */
    public List<Employee> findAll() throws SQLException {
        String sql = "SELECT " + COLUMNS + " FROM employees ORDER BY id";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            return readAll(rs);
        }
    }

    /**
     * Search by name (partial, case-insensitive) or by exact employee ID.
     * If the keyword is a number, employees with that ID are matched as well.
     */
    public List<Employee> search(String keyword) throws SQLException {
        boolean looksLikeId = keyword.matches("\\d{1,9}");
        String sql = "SELECT " + COLUMNS + " FROM employees WHERE name LIKE ?"
                + (looksLikeId ? " OR id = ?" : "")
                + " ORDER BY id";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, "%" + escapeLike(keyword) + "%");
            if (looksLikeId) {
                ps.setInt(2, Integer.parseInt(keyword));
            }
            try (ResultSet rs = ps.executeQuery()) {
                return readAll(rs);
            }
        }
    }

    /** Returns the employee with this ID, or null if none exists. */
    public Employee findById(int id) throws SQLException {
        String sql = "SELECT " + COLUMNS + " FROM employees WHERE id = ?";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? mapRow(rs) : null;
            }
        }
    }

    /** Inserts a new employee and returns the ID generated by the database. */
    public int insert(Employee e) throws SQLException {
        String sql = "INSERT INTO employees (name, email, phone, department, job_title, salary, joining_date) "
                + "VALUES (?, ?, ?, ?, ?, ?, ?)";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, e.getName());
            ps.setString(2, e.getEmail());
            ps.setString(3, e.getPhone());
            ps.setString(4, e.getDepartment());
            ps.setString(5, e.getJobTitle());
            ps.setBigDecimal(6, e.getSalary());
            ps.setObject(7, e.getJoiningDate()); // LocalDate: no time-zone surprises
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                return keys.next() ? keys.getInt(1) : 0;
            }
        }
    }

    /** Updates an employee. Returns false if no employee with that ID exists. */
    public boolean update(Employee e) throws SQLException {
        String sql = "UPDATE employees SET name = ?, email = ?, phone = ?, department = ?, "
                + "job_title = ?, salary = ?, joining_date = ? WHERE id = ?";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, e.getName());
            ps.setString(2, e.getEmail());
            ps.setString(3, e.getPhone());
            ps.setString(4, e.getDepartment());
            ps.setString(5, e.getJobTitle());
            ps.setBigDecimal(6, e.getSalary());
            ps.setObject(7, e.getJoiningDate()); // LocalDate: no time-zone surprises
            ps.setInt(8, e.getId());
            return ps.executeUpdate() == 1;
        }
    }

    /** Deletes an employee. Returns false if no employee with that ID exists. */
    public boolean delete(int id) throws SQLException {
        String sql = "DELETE FROM employees WHERE id = ?";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, id);
            return ps.executeUpdate() == 1;
        }
    }

    /**
     * Is this email already used by ANOTHER employee?
     * Pass excludeId = 0 when adding; pass the employee's own ID when editing.
     */
    public boolean emailExists(String email, int excludeId) throws SQLException {
        String sql = "SELECT COUNT(*) FROM employees WHERE email = ? AND id <> ?";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, email);
            ps.setInt(2, excludeId);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() && rs.getInt(1) > 0;
            }
        }
    }

    // ---------- Dashboard statistics ----------

    public int countEmployees() throws SQLException {
        return readInt("SELECT COUNT(*) FROM employees");
    }

    public int countDepartments() throws SQLException {
        return readInt("SELECT COUNT(DISTINCT department) FROM employees");
    }

    /** The most recently added employees (highest IDs first). */
    public List<Employee> findRecent(int limit) throws SQLException {
        String sql = "SELECT " + COLUMNS + " FROM employees ORDER BY id DESC LIMIT ?";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setInt(1, limit);
            try (ResultSet rs = ps.executeQuery()) {
                return readAll(rs);
            }
        }
    }

    /** Department names already used (to suggest them in the form). */
    public List<String> findDepartments() throws SQLException {
        String sql = "SELECT DISTINCT department FROM employees ORDER BY department";
        List<String> list = new ArrayList<>();
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                list.add(rs.getString(1));
            }
        }
        return list;
    }

    // ---------- private helpers ----------

    private int readInt(String sql) throws SQLException {
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            return rs.next() ? rs.getInt(1) : 0;
        }
    }

    private List<Employee> readAll(ResultSet rs) throws SQLException {
        List<Employee> list = new ArrayList<>();
        while (rs.next()) {
            list.add(mapRow(rs));
        }
        return list;
    }

    /** Converts the current row of a ResultSet into an Employee object. */
    private Employee mapRow(ResultSet rs) throws SQLException {
        Employee e = new Employee();
        e.setId(rs.getInt("id"));
        e.setName(rs.getString("name"));
        e.setEmail(rs.getString("email"));
        e.setPhone(rs.getString("phone"));
        e.setDepartment(rs.getString("department"));
        e.setJobTitle(rs.getString("job_title"));
        e.setSalary(rs.getBigDecimal("salary"));
        e.setJoiningDate(rs.getObject("joining_date", LocalDate.class));
        Timestamp created = rs.getTimestamp("created_at");
        if (created != null) {
            e.setCreatedAt(created.toLocalDateTime());
        }
        return e;
    }

    /** Makes % and _ typed by the user act as normal characters inside a LIKE pattern. */
    private String escapeLike(String text) {
        return text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_");
    }
}
